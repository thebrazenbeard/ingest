"""Read-only audit of the installed standalone Ingest Python package boundary.

Run independently of ``import ingest``: that import might already have been
overwritten by another distribution claiming the same top-level package.

This checks PEP 376 installed RECORD declarations and SHA-256 hashes. It cannot
prevent pip from overwriting files, validate wheel signatures, or certify that
every import path on ``sys.path`` has trustworthy metadata. A non-PASS result
must block any decision to co-install or invoke a contaminated Ingest runtime.
"""

from __future__ import annotations

import base64
import csv
import hashlib
from importlib import metadata
from io import StringIO
import json
from pathlib import Path, PurePosixPath
import re
import sys
from typing import Iterable


TARGET = "vera-ingest"
SCHEMA = "INGEST_INSTALL_OWNERSHIP_V1"
_SHA256_DIGEST = re.compile(r"[A-Za-z0-9_-]{43}\Z")


def _name(distribution: metadata.Distribution) -> str:
    raw = distribution.metadata.get("Name", "")
    return re.sub(r"[-_.]+", "-", raw).lower()


def _recorded_import_path(record: str, *, ignore_generated_cache: bool = False) -> tuple[str | None, bool]:
    """Return package-relative file path and whether the RECORD path is unsafe.

    An import-package directory named ``ingest`` must occur at the canonical
    relative root with exactly one spelling. A CLI script named ``ingest`` is
    not an import directory. Only target-owned generated bytecode caches are
    excluded from hash qualification; foreign bytecode claims remain visible.
    """
    path = PurePosixPath(record)
    parts = path.parts
    # An installed CLI script named ``ingest`` (often ../../../bin/ingest)
    # is not an import-package path. Only a directory named ingest that
    # contains a file can claim this package root.
    normalized_parts = record.replace("\\", "/").split("/")
    # RECORD names may be interpreted on a case-insensitive filesystem. A
    # differently cased alias must not make a foreign package invisible.
    mentions_ingest = any(part.casefold() == "ingest" and i < len(normalized_parts) - 1
                          for i, part in enumerate(normalized_parts))
    if not mentions_ingest:
        return None, False
    if (
        path.is_absolute()
        or ".." in parts
        or "\\" in record
        or not parts
        or parts[0] != "ingest"
        or len(parts) < 2
        # PurePosixPath silently collapses ./ and repeated separators; accept
        # only one canonical spelling for an import-package RECORD claim.
        or str(path) != record
    ):
        return None, True
    # pip generates un-hashed .pyc entries inside __pycache__ for the target
    # distribution. Ignore *only those target-owned generated cache entries*;
    # importable root-level .pyc and foreign cache claims require scrutiny.
    if ignore_generated_cache and "__pycache__" in parts[1:-1] and path.suffix == ".pyc":
        return None, False
    return str(path), False


def _hash_matches(distribution: metadata.Distribution, path: str, expected_hash: str, expected_size: str) -> bool:
    if not expected_hash.startswith("sha256="):
        return False
    digest_value = expected_hash.removeprefix("sha256=")
    if not _SHA256_DIGEST.fullmatch(digest_value) or not expected_size.isdecimal():
        return False
    target = Path(distribution.locate_file(path))
    root = Path(distribution.locate_file(""))
    # A packaged file must be physically inside its declared installation
    # location; do not read symlink redirects to private or unrelated paths.
    if target.is_symlink() or not target.is_file():
        return False
    if not target.resolve().is_relative_to(root.resolve()):
        return False
    digest = hashlib.sha256()
    size = 0
    try:
        with target.open("rb") as handle:
            for block in iter(lambda: handle.read(1024 * 1024), b""):
                size += len(block)
                digest.update(block)
    except OSError:
        return False
    encoded = base64.urlsafe_b64encode(digest.digest()).decode("ascii").rstrip("=")
    if encoded != digest_value:
        return False
    if size != int(expected_size):
        return False
    return True


def audit_ownership(distributions: Iterable[metadata.Distribution] | None = None) -> dict:
    """Audit installed file ownership; no package import, file write, or network.

    An explicit iterable supports tests with real synthetic ``.dist-info``
    metadata in a disposable site directory.
    """
    if distributions is None:
        distributions = metadata.distributions()
    claims: dict[str, set[str]] = {}
    owned_paths: set[str] = set()
    invalid: set[str] = set()
    unverified: set[str] = set()
    unclaimed_top_level: set[str] = set()
    target_count = 0

    for distribution in distributions:
        owner = _name(distribution)
        if not owner:
            continue
        if owner == TARGET:
            target_count += 1
        top_level = distribution.read_text("top_level.txt") or ""
        claims_top_level = any(line.strip().casefold() == "ingest" for line in top_level.splitlines())
        if owner != TARGET and claims_top_level:
            # RECORD is the file authority, but a second distribution that
            # declares this import root without matching code files (e.g. an
            # editable install) cannot be silently certified as non-owner.
            unclaimed_top_level.add(owner)
        raw_record = distribution.read_text("RECORD")
        if raw_record is None:
            if owner == TARGET or claims_top_level:
                unverified.add(owner)
            continue
        try:
            records = list(csv.reader(StringIO(raw_record)))
        except csv.Error:
            unverified.add(owner)
            continue
        for record in records:
            if len(record) != 3:
                unverified.add(owner)
                continue
            path, entry_hash, entry_size = record
            relpath, unsafe = _recorded_import_path(path, ignore_generated_cache=(owner == TARGET))
            if unsafe:
                unverified.add(owner)
                continue
            if relpath is None:
                continue
            if owner in claims.get(relpath, ()):
                unverified.add(owner)
            claims.setdefault(relpath, set()).add(owner)
            if owner == TARGET:
                owned_paths.add(relpath)
                if not _hash_matches(distribution, path, entry_hash, entry_size):
                    invalid.add(relpath)

    foreign = {owner for owners in claims.values() for owner in owners if owner != TARGET}
    unverified.update(unclaimed_top_level - foreign)
    overlap = {path for path, owners in claims.items() if TARGET in owners and len(owners) > 1}
    if target_count == 0:
        status = "NOT_INSTALLED"
    elif target_count != 1 or not owned_paths or unverified:
        status = "UNKNOWN"
    elif foreign:
        status = "COLLISION"
    elif invalid:
        status = "INTEGRITY_FAILURE"
    else:
        status = "PASS"
    return {
        "schema": SCHEMA,
        "status": status,
        "target": TARGET,
        "owned_files": len(owned_paths),
        "foreign_owners": sorted(foreign),
        "overlapping_paths": sorted(overlap),
        "invalid_files": sorted(invalid),
        "unverified_owners": sorted(unverified),
    }


def main() -> int:
    report = audit_ownership()
    print(json.dumps(report, sort_keys=True, separators=(",", ":")))
    return 0 if report["status"] == "PASS" else 2


if __name__ == "__main__":
    sys.exit(main())
